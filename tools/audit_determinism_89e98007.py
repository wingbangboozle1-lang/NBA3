#!/usr/bin/env python3
"""Determinism audit (session 89e98007): which published artefacts still depend on the interpreter.

Companion to scripts/determinism.py. CI re-derives committed artefacts and compares bytes, so every
file that (a) is regenerated by the refresh chain and (b) computes a float with the interpreter's
``sum()``/``round()`` carries the same latent failure that froze the pipeline for six days
(EVE-F04: CPython >= 3.12 compensates ``sum()``, see docs.python.org/3/whatsnew/3.12.html).

This script does not fix anything. It lists, per file: bare ``sum(``/``round(`` call counts, whether
the file writes a committed artefact, whether the refresh workflow replays it as a hard gate
(``--check``), and whether another session currently owns it. Files under another session's claim are
reported and left alone; the owner gets a change request in COORDINATION.md.

Run: python3 tools/audit_determinism_89e98007.py [--markdown out.md]
"""
from __future__ import annotations

import argparse
import ast
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))

# Files the refresh workflow replays with a hard byte-comparison gate. GATE = blocks a rebuild.
GATED = {
    "scripts/capture_2ecbccfd.py", "scripts/gamebooks_2ecbccfd.py",
    "scripts/slate_extra_2ecbccfd.py", "scripts/model_2ecbccfd.py",
    "scripts/ledger_2ecbccfd.py", "round_2ecbccfd/build.py",
}
# Run by scripts/refresh_official.py step 6 (writes committed files, no --check replay here).
REFRESH_RUN = {
    "scripts/standings_feed.py", "scripts/results_feed.py", "scripts/pick_ledger.py",
    "scripts/estimators.py", "scripts/estimators_round_79341829.py", "scripts/minutes_model.py",
    "scripts/assemble_canonical.py", "scripts/build_app.py", "scripts/freshness_gates.py",
    "scripts/publish_picks.py", "scripts/injury_archive.py", "scripts/refresh_official.py",
}
# Owned by the one active claim when this session started (PR #143) — reported, never edited here.
OTHER_SESSION = {
    "scripts/build_app.py", "scripts/pick_ledger.py", "scripts/capture_round_79341829.py",
    "scripts/roll_915d2e99.py", "scripts/run_suite_battery.py",
}
WRITES = re.compile(r"""open\([^)]*["'](w|a)""")


def scan(rel):
    path = os.path.join(ROOT, rel)
    with open(path, encoding="utf-8") as fh:
        src = fh.read()
    try:
        tree = ast.parse(src)
    except SyntaxError:
        return None
    n_sum = n_round = 0
    writes = bool(WRITES.search(src)) or "json.dump(" in src
    for n in ast.walk(tree):
        if isinstance(n, ast.Call) and isinstance(n.func, ast.Name):
            if n.func.id == "sum":
                n_sum += 1
            elif n.func.id == "round":
                n_round += 1
    pinned = "import determinism as det" in src
    return n_sum, n_round, writes, pinned


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--markdown", default="")
    a = ap.parse_args()
    files = []
    for d in ("scripts", "round_2ecbccfd", "tools"):
        for f in sorted(os.listdir(os.path.join(ROOT, d))):
            if f.endswith(".py") and not f.startswith("__"):
                files.append(f"{d}/{f}")
    rows = []
    for rel in files:
        r = scan(rel)
        if not r:
            continue
        n_sum, n_round, writes, pinned = r
        if n_sum == 0 and n_round == 0:
            continue
        if rel in GATED:
            state = "GATED — pinned" if pinned else "GATED — AT RISK"
        elif rel in REFRESH_RUN:
            state = "refresh-run, writes committed output" + ("" if pinned else " — at risk")
        elif writes:
            state = "writes committed output" + ("" if pinned else " — at risk")
        else:
            state = "no artefact written"
        owner = "arena/915d2e99-nba3 (PR #143)" if rel in OTHER_SESSION else "unowned"
        rows.append((rel, n_sum, n_round, state, owner))
    lines = [
        "# Determinism audit — interpreter dependence in the published build chain",
        "",
        f"Generated by `python3 tools/audit_determinism_89e98007.py` (session `89e98007`, 2026-11-19).",
        "",
        "Context: `data/rounds/2026-11-17/**` and `round_2ecbccfd/*.html` are re-derived by CI and",
        "compared byte-for-byte with the committed files. CPython >= 3.12 sums floats with Neumaier",
        "compensation ([3.12 What's New](https://docs.python.org/3/whatsnew/3.12.html),",
        "[`sum()`](https://docs.python.org/3/library/functions.html#sum)), which is why run",
        "[44469939831](https://github.com/wingbangboozle1-lang/NBA3/actions/runs/44469939831) went red",
        "on the runner's Python 3.14.4 while every suite passed on 3.11. The rule is now pinned in",
        "`scripts/determinism.py` (`det.fold`, `det.dq`) for the gated chain.",
        "",
        "| file | bare `sum(` | bare `round(` | exposure | owner |",
        "|---|---|---|---|---|",
    ]
    for rel, n_sum, n_round, state, owner in rows:
        lines.append(f"| `{rel}` | {n_sum} | {n_round} | {state} | {owner} |")
    lines += [
        "",
        "## What this session changed and why nothing else moved",
        "",
        "- Pinned: the six files CI replays as hard gates. Regenerating all of them on the pinned rule",
        "  reproduces every committed byte (`git status` clean after six `--check` runs; probe in",
        "  `data/rounds/2026-11-19-89e98007/runner_probe.md` on the runner itself).",
        "- Not pinned here: `scripts/build_app.py`, `scripts/pick_ledger.py` and the other files the",
        "  active claim (PR #143) touches. They regenerate `data/app/**` on the runner during a",
        "  refresh rather than being byte-checked, so a rule change there is a *republish* of live",
        "  data, not a gate fix — that is the owner's call, logged as CR-89E-01/04.",
        "- Residual, accepted: `f\"{x:.2f}\"` formatting inside generated HTML. Float formatting is",
        "  specified as correctly rounded from the value itself (`float.__format__`,",
        "  https://docs.python.org/3/library/stdtypes.html#float.__format__) and the inputs here are",
        "  already-pinned artefact values, so no interpreter-dependent summation reaches a page.",
        "",
        "## Rules for extending the pin (why this sweep stopped at six files)",
        "",
        "1. A pin is only safe where the committed artefact was produced by the pre-3.12 fold. It is",
        "   byte-identical to that interpreter's builtins, so re-running the generator changes nothing.",
        "2. `scripts/estimators.py`, `results_feed.py`, `minutes_model.py`, `assemble_canonical.py`,",
        "   `build_app.py`, `model.py` and the site builders are regenerated *on the runner* and their",
        "   output is what the next refresh commits. Re-pinning them to the naive fold would move live",
        "   published numbers (e.g. the 0.1088 -> 0.1087 minute share) and read as a data change. The",
        "   right fix for that half is to pin the interpreter in the workflow (CR-89E-02) and, if the",
        "   owner wants the more accurate summation, to republish deliberately in one reviewed commit.",
        "3. The one-shot `capture_official_*` / `round*` scripts in the table above already wrote their",
        "   artefacts; their committed outputs are the record, and re-running them is not part of CI.",
        "   They are listed so nobody re-runs one on a newer interpreter and mistakes the diff for",
        "   moved data.",
        "",
        "## Measured: what an interpreter change actually moves today",
        "",
        "Re-ran every generator the refresh rebuild chain calls, twice, in a scratch tree: once plain,",
        "once with a `sitecustomize` that installs the CPython >= 3.12 compensated float summation",
        "(the runner's behaviour, emulated). Only one published file moved:",
        "",
        "| generator | committed artefact | bytes changed under compensation |",
        "|---|---|---|",
        "| `scripts/capture_round_79341829.py` | `data/app/minutes_shares.json` | 1 line: `teams.2026-11-14:MIA.top8[6].share` 0.0843 -> 0.0842 |",
        "| `scripts/estimators.py` | `data/app/estimators.json` | none |",
        "| `scripts/minutes_model.py` | `data/app/rotation_impact.json` | none |",
        "| `scripts/assemble_canonical.py` | `data/app/canonical.json` | none |",
        "| `scripts/injury_archive.py` | `data/app/injury_reports_archive/` | none |",
        "| `scripts/freshness_gates.py` | `data/live/freshness.json` | none (12/12 gates) |",
        "",
        "Before this session's fix the same emulation moved `data/rounds/2026-11-17/"
        "player_logs_2026-11-15.json` (`.top8_minutes_shares.2026-11-15:WAS.top8[4].share`,"
        " 0.1088 -> 0.1087) — the field that has failed the preflight since 2026-11-17. After it, the"
        " five replayed generators and the site build reproduce their committed bytes exactly.",
        "",
        "Reproduce: `PYTHONPATH=<dir containing a sitecustomize that sets builtins.sum to Neumaier>"
        " python3 <generator>`, then `git status`. The emulator used by the test suite is in"
        " `tests/test_determinism_89e98007.py`.",
        "",
        "## Decision this audit surfaces for the owner",
        "",
        "The pinned rule is the *less accurate* summation on purpose: it is the one that generated the",
        "numbers the sealed pick ledger hashed. Moving to compensated summation would change published",
        "values (0.1088 -> 0.1087 for the Washington minute share) and therefore should be done as an",
        "explicit republish with a new ledger epoch, not as a drive-by fix. Flagged for review.",
        "",
    ]
    md = "\n".join(lines)
    if a.markdown:
        with open(os.path.join(ROOT, a.markdown), "w", encoding="utf-8") as fh:
            fh.write(md + "\n")
        print(f"wrote {a.markdown} ({len(rows)} rows)")
    else:
        print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
