def build_finals(fin: dict) -> None:
    rows = []
    for g in fin["games"]:
        c = g["checks"]
        per_away = " / ".join(str(x) for x in g["away_periods_book"])
        per_home = " / ".join(str(x) for x in g["home_periods_book"])
        if "period_table_vs_summary_conflict" in c:
            t = c["period_table_vs_summary_conflict"]
            per_home = (f'{per_home} <span class="badge warn">table</span><br>'
                        f'<span class="small">summary line: {" / ".join(str(x) for x in t["summary_home_periods"])}</span>')
        status = g["status"]
        cls = "warn" if "CONFLICTING" in status else ("ok" if status.startswith("VERIFIED") else "bad")
        rows.append(
            "<tr>"
            f"<td>{e(g['date'])}</td>"
            f"<td>{e(g['away_name'])} <span class='small'>({e(g['away'])})</span><br>at {e(g['home_name'])} <span class='small'>({e(g['home'])})</span></td>"
            f"<td class='num'>{e(g['away_final'])} – {e(g['home_final'])}<br><span class='small'>{e(g['state_on_schedule'])}</span></td>"
            f"<td>{e(g['away'])}: {per_away}<br>{e(g['home'])}: {per_home}</td>"
            f"<td><span class='badge {cls}'>{e(status)}</span></td>"
            f"<td>{'yes' if g['on_pr98_branch'] else 'no'} <span class='small'>(PR #98 branch)</span><br>"
            f"<span class='small'>main results feed: no</span></td>"
            f"<td>{official_links([s['url'] for s in g['sources']])}</td>"
            "</tr>")
    counts = fin["counts"]
    tiles = (f'<div class="tiles">'
             f'<div class="tile"><div class="n">{counts["games"]}</div><div class="l">Final on nba.com</div></div>'
             f'<div class="tile"><div class="n">{counts["verified"]}</div><div class="l">final + quarters verified</div></div>'
             f'<div class="tile"><div class="n">{counts["final_verified_quarter_conflict"]}</div><div class="l">final verified, quarter split conflicting (K-02)</div></div>'
             f'<div class="tile"><div class="n">{counts["on_main_results_feed"]}</div><div class="l">on main results feed</div></div>'
             f'<div class="tile"><div class="n">{counts["on_pr98_branch"]}</div><div class="l">on open PR #98 branch</div></div></div>')
    body = (tiles +
            '<div class="note"><b>Method.</b> Final score: the official nba.com schedule. Period scores: the official '
            'statsdmz game book (SCORE BY PERIOD table, and the one-line summary at the foot of the same book). '
            'A game counts as verified only when the schedule final equals the book final and the quarters sum to it. '
            'Values are transcribed by hand from the fetch tool and the arithmetic is recomputed by '
            '<code>make_data.py</code>.</div>'
            '<div class="note warn"><b>Not a settlement.</b> These are independent reads for the owners of PR #98 and the '
            'scheduled refresh. The ledger and results feed on main are unchanged by this audit.</div>'
            '<div class="scroll"><table><thead><tr><th>Date</th><th>Game</th><th class="num">Final (away – home)</th>'
            '<th>Period scores (away / home)</th><th>Status</th><th>Where it is</th><th>Official sources</th></tr></thead>'
            f'<tbody>{"".join(rows)}</tbody></table></div>')
    page("finals.html", "11/15 finals — independent official read",
         "All nine games on the 2026-11-15 slate, read from the official schedule and game books.",
         body, fin["retrieved"])


def build_injuries(inj: dict) -> None:
    pub = inj["published_on_main"]
    banner = (f'<div class="note bad"><b>Banner on main:</b> revision {e(pub["banner_revision_time"])} · '
              f'retrieval {" and ".join(e(t) for t in pub["banner_retrieval_times"])}. '
              f'<span class="small">{e(pub["note"])}</span></div>'
              f'<div class="note bad"><b>Official index:</b> {inj["reports_listed_for_2026_11_16"]} reports listed for '
              f'2026-11-16; the newest is <b>{e(inj["newest_listed"])}</b>. The listing ends there. '
              f'The PDFs themselves were not fetched in this audit.</div>'
              f'<div class="note">{e(inj["gap"])}</div>')
    rows = []
    for i, r in enumerate(inj["reports"], 1):
        rows.append(f"<tr><td class='num'>{i}</td><td>{e(r['revision_et'])}</td>"
                    f"<td>{link(r['pdf_url'], r['pdf_url'].rsplit('/', 1)[-1])}</td>"
                    f"<td><span class='badge muted'>not captured</span></td>"
                    f"<td>{link(inj['source']['url'], 'official index')}</td></tr>")
    body = (banner +
            '<div class="scroll"><table><thead><tr><th class="num">#</th><th>Revision (ET)</th><th>Official PDF</th>'
            '<th>Captured here</th><th>Official source</th></tr></thead>'
            f'<tbody>{"".join(rows)}</tbody></table></div>')
    page("injuries.html", "Injury report index — 2026-11-16",
         "Every report the official index lists for today, against what the banner on main shows.",
         body, inj["retrieved"])


