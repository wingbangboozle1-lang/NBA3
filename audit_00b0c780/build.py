"""Build the static audit pages for session arena/00b0c780-nba3 from audit_00b0c780/data/*.json.

Deterministic: no wall clock, no network. Every number on a page comes from a JSON file in
data/, which make_data.py wrote from transcribed official values.

Run:  python3 audit_00b0c780/build.py      (writes audit_00b0c780/pages/*.html)
"""
