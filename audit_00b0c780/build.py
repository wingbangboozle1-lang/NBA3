def load(name: str) -> dict:
    return json.loads((DATA / name).read_text(encoding="utf-8"))


def e(x) -> str:
    return html.escape("" if x is None else str(x), quote=True)


def link(url: str, label: str | None = None) -> str:
    return f'<a href="{e(url)}" rel="noopener">{e(label or url)}</a>'


def official_links(urls) -> str:
    urls = [u for u in urls if u]
    if not urls:
        return '<span class="none">no official link on this row</span>'
    return " · ".join(link(u, u.split("//", 1)[-1].split("/", 1)[0] + "/…") for u in urls)


def badge(text: str) -> str:
    """ok = fully met; warn = partly met, built but stale or negative; bad = failing, not met or blocked."""
    if text == "Met":
        cls = "ok"
    elif text.startswith(("Met (partly)", "Built, stale", "Built, one-day", "Built, negative")):
        cls = "warn"
    else:
        cls = "bad"
    return f'<span class="badge {cls}">{e(text)}</span>'


